let currentLang = localStorage.getItem('clinic_lang') || 'en';

function setLanguage(lang) {
  if (!i18nData[lang]) return;
  currentLang = lang;
  localStorage.setItem('clinic_lang', lang);
  document.documentElement.setAttribute('lang', lang);

  const dict = i18nData[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (typeof dict[key] === 'string') {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (typeof dict[key] === 'string') {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Top header dark strip buttons
  document.querySelectorAll('.lang-btn-strip').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.classList.add('active', 'bg-brand-700', 'text-white');
      btn.classList.remove('text-slate-300');
    } else {
      btn.classList.remove('active', 'bg-brand-700', 'text-white');
      btn.classList.add('text-slate-300');
    }
  });

  // Main navigation & mobile drawer buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.classList.add('active', 'bg-brand-700', 'text-white');
      btn.classList.remove('text-slate-600');
    } else {
      btn.classList.remove('active', 'bg-brand-700', 'text-white');
      btn.classList.add('text-slate-600');
    }
  });

  if (typeof updatePainDetail === 'function') {
    const activeChip = document.querySelector('.pain-chip.active');
    const painType = activeChip ? activeChip.getAttribute('data-pain') : 'back';
    updatePainDetail(painType);
  }

  if (typeof window.goToStretchStep === 'function') {
    const activeTab = document.querySelector('.routine-tab.active');
    const currentStep = activeTab ? parseInt(activeTab.getAttribute('data-step'), 10) : 0;
    window.goToStretchStep(currentStep);
  }

  if (typeof renderLucideIcons === 'function') {
    renderLucideIcons();
  }
}

window.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn, .lang-btn-strip').forEach(btn => {
    btn.addEventListener('click', () => {
      const targetLang = btn.getAttribute('data-lang');
      setLanguage(targetLang);
    });
  });

  setLanguage(currentLang);
});
